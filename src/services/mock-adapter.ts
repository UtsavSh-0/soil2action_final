/**
 * DEVELOPMENT-ONLY mock adapter. Never active in production builds.
 * Every response is flagged `is_mock: true` and labelled in the UI.
 * Mock output contains NO agronomic advice — only placeholders that show layout.
 */
import type {
  FieldInput,
  FieldProfile,
  HistoryQuery,
  Paginated,
  ParameterAssessment,
  SoilAnalysisRequest,
  SoilAnalysisResponse,
  SoilReport,
} from "@/types/api";
import { ApiError } from "@/types/api";

const REPORTS_KEY = "s2a.mock.reports";
const FIELDS_KEY = "s2a.mock.fields";
const delay = (ms = 700) => new Promise((r) => setTimeout(r, ms));
const uid = () => Math.random().toString(36).slice(2, 10);

function load<T>(key: string): T[] {
  try {
    return JSON.parse(localStorage.getItem(key) ?? "[]") as T[];
  } catch {
    return [];
  }
}
function save<T>(key: string, v: T[]) {
  localStorage.setItem(key, JSON.stringify(v));
}

function param(key: string, label: string, value: number | null, unit: string | null): ParameterAssessment {
  return {
    key,
    label,
    value,
    unit,
    status: "unknown",
    explanation: value === null ? "Not measured." : "Mock: status is decided by the backend.",
  };
}

export const mockApi = {
  async health() {
    await delay(150);
    return { status: "ok (mock)" };
  },
  async analyze(req: SoilAnalysisRequest): Promise<SoilAnalysisResponse> {
    await delay(1200);
    const m = req.measurements;
    const id = `mock-${uid()}`;
    const missing = [
      m.electrical_conductivity === null && "Electrical conductivity",
      m.organic_carbon === null && "Organic carbon",
    ].filter(Boolean) as string[];
    const analysis: SoilAnalysisResponse = {
      report_id: id,
      created_at: new Date().toISOString(),
      is_mock: true,
      overall_assessment: {
        label: "Mock result",
        score: null,
        summary: "This is a development mock. Connect the FastAPI backend to get a real soil assessment.",
        summary_hi: null,
      },
      parameters: [
        param("ph", "pH", m.ph, null),
        param("electrical_conductivity", "Electrical conductivity", m.electrical_conductivity, "dS/m"),
        param("organic_carbon", "Organic carbon", m.organic_carbon, "%"),
        param("nitrogen", "Nitrogen (N)", m.nitrogen, "kg/ha"),
        param("phosphorus", "Phosphorus (P)", m.phosphorus, "kg/ha"),
        param("potassium", "Potassium (K)", m.potassium, "kg/ha"),
      ],
      concerns: ["Mock: concerns will be returned by the backend."],
      crop_guidance: [
        { crop: req.field.intended_crop ?? req.field.current_crop, suitability: "unknown", notes: "Mock: no crop guidance generated." },
      ],
      recommendations: [
        {
          id: uid(),
          priority: "high",
          title: "[Mock] Placeholder action",
          reason: "Shows how a backend recommendation will appear.",
          input: null,
          quantity: null,
          unit: null,
          timing: null,
          estimated_cost: null,
          cautions: ["Not real advice."],
        },
      ],
      confidence: null,
      limitations: ["Generated by the development mock adapter."],
      missing_information: missing,
    };
    const report: SoilReport = {
      report_id: id,
      created_at: analysis.created_at,
      status: "completed",
      field_id: req.field.id ?? null,
      field_name: req.field.name,
      field_size: req.field.size,
      field_size_unit: req.field.size_unit,
      crop: req.field.current_crop,
      farmer_name: req.farmer.name,
      measurements: m,
      request: req,
      analysis,
      is_mock: true,
    };
    save(REPORTS_KEY, [report, ...load<SoilReport>(REPORTS_KEY)]);
    return analysis;
  },
  async history(q: HistoryQuery): Promise<Paginated<SoilReport>> {
    await delay(400);
    const items = load<SoilReport>(REPORTS_KEY);
    return { items, total: items.length, page: q.page ?? 1, page_size: q.page_size ?? items.length };
  },
  async report(id: string): Promise<SoilReport> {
    await delay(300);
    const r = load<SoilReport>(REPORTS_KEY).find((x) => x.report_id === id);
    if (!r) throw new ApiError("http", "Report not found", 404);
    return r;
  },
  async deleteReport(id: string) {
    await delay(300);
    save(REPORTS_KEY, load<SoilReport>(REPORTS_KEY).filter((x) => x.report_id !== id));
  },
  async fields(): Promise<FieldProfile[]> {
    await delay(300);
    return load<FieldProfile>(FIELDS_KEY);
  },
  async createField(input: FieldInput): Promise<FieldProfile> {
    await delay(300);
    const f: FieldProfile = { ...input, id: `mock-${uid()}`, created_at: new Date().toISOString() };
    save(FIELDS_KEY, [...load<FieldProfile>(FIELDS_KEY), f]);
    return f;
  },
  async updateField(id: string, input: FieldInput): Promise<FieldProfile> {
    await delay(300);
    const all = load<FieldProfile>(FIELDS_KEY);
    const idx = all.findIndex((f) => f.id === id);
    if (idx < 0) throw new ApiError("http", "Field not found", 404);
    const updated: FieldProfile = { ...(all[idx] as FieldProfile), ...input, id };
    all[idx] = updated;
    save(FIELDS_KEY, all);
    return updated;
  },
};
