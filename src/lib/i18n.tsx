type Vars = Record<string, string | number>;
interface Ctx {
  lang: Language;
  setLang: (l: Language) => void;
  t: (k: TKey, vars?: Vars) => string;
}

const I18nContext = createContext<Ctx | null>(null);

export function translate(lang: Language, k: TKey, vars?: Vars) {
  let s: string = (lang === "hi" ? hi[k] : undefined) ?? en[k];
  if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, String(v));
  return s;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("en");
  useEffect(() => {
    const saved = localStorage.getItem("s2a.lang");
    if (saved === "hi" || saved === "en") setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Language) => {
    setLangState(l);
    localStorage.setItem("s2a.lang", l);
  }, []);
  const t = useCallback((k: TKey, vars?: Vars) => translate(lang, k, vars), [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
